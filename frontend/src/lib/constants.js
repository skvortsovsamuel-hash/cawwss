export function formatLocation({ address, room, city, state, zip_code, location }) {
  const parts = [];
  if (address) parts.push(address + (room ? `, ${room}` : ""));
  if (city && state) parts.push(`${city}, ${state}`);
  else if (state) parts.push(state);
  if (zip_code) parts.push(zip_code);
  const combined = parts.join(" · ");
  return combined || location || "";
}
